import javax.imageio.ImageIO;
import java.awt.image.BufferedImage;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Map;
import java.util.TreeMap;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.zip.ZipEntry;
import java.util.zip.ZipFile;

/**
 * Builds core/src/main/resources/capella/block_colors.txt from a Minecraft client jar: for every
 * block with a blockstate file, the alpha-weighted average colour of its side and top textures.
 * Run: java tools/colors/BlockColorTable.java <minecraft-client.jar> <out.txt>
 */
public class BlockColorTable {
    static final Pattern MODEL = Pattern.compile("\"model\"\\s*:\\s*\"(?:minecraft:)?([^\"]+)\"");
    static final Pattern TEX = Pattern.compile("\"(\\w+)\"\\s*:\\s*\"#?(?:minecraft:)?([^\"]+)\"");
    static final Pattern PARENT = Pattern.compile("\"parent\"\\s*:\\s*\"(?:minecraft:)?([^\"]+)\"");

    public static void main(String[] args) throws Exception {
        try (ZipFile jar = new ZipFile(args[0])) {
            Map<String, String> out = new TreeMap<>();
            var entries = jar.entries();
            while (entries.hasMoreElements()) {
                ZipEntry e = entries.nextElement();
                String n = e.getName();
                if (!n.startsWith("assets/minecraft/blockstates/") || !n.endsWith(".json")) continue;
                String block = n.substring("assets/minecraft/blockstates/".length(), n.length() - 5);
                Matcher m = MODEL.matcher(read(jar, n));
                if (!m.find()) continue;
                Map<String, String> tex = textures(jar, m.group(1));
                String side = pick(tex, "side", "all", "texture", "wall", "pane", "cross", "particle", "end", "top");
                String top = pick(tex, "top", "end", "all", "texture", "side", "particle");
                Integer s = side == null ? null : average(jar, side);
                Integer t = top == null ? null : average(jar, top);
                if (s == null && t == null) continue;
                if (s == null) s = t;
                if (t == null) t = s;
                out.put(block, String.format("%06X %06X", s, t));
            }
            StringBuilder sb = new StringBuilder("# block side top (average texture RGB), generated by tools/colors/BlockColorTable.java\n");
            out.forEach((k, v) -> sb.append(k).append(' ').append(v).append('\n'));
            Files.writeString(Path.of(args[1]), sb.toString());
            System.out.println(out.size() + " blocks");
        }
    }

    static String pick(Map<String, String> tex, String... keys) {
        for (String k : keys) {
            String v = tex.get(k);
            if (v != null && !v.startsWith("#") && tex.containsKey(k)) return v;
        }
        return null;
    }

    /** The model's textures with its parents', #references resolved. */
    static Map<String, String> textures(ZipFile jar, String model) throws Exception {
        Map<String, String> tex = new TreeMap<>();
        String cur = model;
        for (int depth = 0; cur != null && depth < 8; depth++) {
            String path = "assets/minecraft/models/" + cur + ".json";
            if (jar.getEntry(path) == null) break;
            // 26.x texture entries may be objects: {"force_translucent": true, "sprite": "..."}.
            String json = read(jar, path).replaceAll("\\{[^{}]*\"sprite\"\\s*:\\s*(\"[^\"]+\")[^{}]*\\}", "$1");
            int ti = json.indexOf("\"textures\"");
            if (ti >= 0) {
                int end = json.indexOf('}', ti);
                Matcher m = TEX.matcher(json.substring(ti, end));
                while (m.find()) tex.putIfAbsent(m.group(1), (json.substring(ti, end).contains("\"#" + m.group(2)) ? "#" : "") + m.group(2));
            }
            Matcher p = PARENT.matcher(json);
            cur = p.find() ? p.group(1) : null;
        }
        for (int pass = 0; pass < 4; pass++) {
            for (var e : tex.entrySet()) {
                if (e.getValue().startsWith("#")) {
                    String r = tex.get(e.getValue().substring(1));
                    if (r != null) e.setValue(r);
                }
            }
        }
        return tex;
    }

    static Integer average(ZipFile jar, String texture) throws Exception {
        ZipEntry e = jar.getEntry("assets/minecraft/textures/" + texture + ".png");
        if (e == null) return null;
        BufferedImage img;
        try (InputStream in = jar.getInputStream(e)) {
            img = ImageIO.read(in);
        }
        int w = img.getWidth(), h = Math.min(img.getHeight(), w); // first frame of animations
        double r = 0, g = 0, b = 0, a = 0;
        for (int y = 0; y < h; y++) {
            for (int x = 0; x < w; x++) {
                int p = img.getRGB(x, y);
                double al = (p >>> 24) / 255.0;
                r += ((p >> 16) & 255) * al;
                g += ((p >> 8) & 255) * al;
                b += (p & 255) * al;
                a += al;
            }
        }
        if (a < 1e-6) return null;
        return ((int) (r / a) << 16) | ((int) (g / a) << 8) | (int) (b / a);
    }

    static String read(ZipFile jar, String path) throws Exception {
        try (InputStream in = jar.getInputStream(jar.getEntry(path))) {
            return new String(in.readAllBytes(), StandardCharsets.UTF_8);
        }
    }
}
